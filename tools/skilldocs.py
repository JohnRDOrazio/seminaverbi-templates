"""python -m tools.skilldocs — regenerate the seminaverbi-editor skill's reference files from config/.

templates.md and categories.md are generated so they cannot drift from the templates and the tree;
the test suite fails when the committed files are stale.
"""
from __future__ import annotations

import json
from pathlib import Path

from sync.categories import load
from sync.pages import LANGS

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("skills") / "seminaverbi-editor"
HEADER = "<!-- Generated by `python -m tools.skilldocs` from config/. Do not edit by hand. -->\n\n"


def _json(root: Path, name: str):
    return json.loads((root / name).read_text(encoding="utf-8"))


def render_templates(root: Path) -> str:
    root = Path(root)
    docs = _json(root, "config/templates.json")
    aliases = _json(root, "config/aliases.json")
    bible = _json(root, "config/bible.json")
    infobox = _json(root, "config/infobox.json")
    by_target: dict[str, list[str]] = {}
    for lang in LANGS:
        for alias, target in sorted(aliases.get(lang, {}).items()):
            by_target.setdefault(target.split(":", 1)[1], []).append(f"{lang}: `{alias.split(':', 1)[1]}`")
    out = [HEADER, "# SV templates\n\n",
           "Identical on all six wikis. Always write the English name; the localized aliases (redirects) "
           "exist so human editors can type a native name.\n"]
    for name in sorted(docs):
        doc = docs[name]
        out.append(f"\n## {name}\n\n{doc['summary']}\n")
        if by_target.get(name):
            out.append(f"\nAliases: {', '.join(by_target[name])}\n")
        if doc["params"]:
            out.append("\n| parameter | meaning |\n|---|---|\n")
            for param, meaning in doc["params"].items():
                out.append(f"| `{param}` | {meaning} |\n")
        if name == "SV Bible quote":
            out.append("\nDefault version per wiki:\n\n| wiki | version |\n|---|---|\n")
            for lang in LANGS:
                out.append(f"| {lang} | {bible['defaults'][lang]} |\n")
        if name == "SV infobox work":
            out.append("\nFields per `type`:\n\n")
            for kind, fields in infobox.items():
                if kind != "person":
                    out.append(f"- `{kind}`: {', '.join(f['key'] for f in fields)}\n")
        if name == "SV infobox person":
            out.append(f"\nFields: {', '.join(f['key'] for f in infobox['person'])}\n")
    return "".join(out)


def render_categories(root: Path) -> str:
    data = load(root)
    out = [HEADER, "# Category tree\n\n",
           "Only these categories may be used. An article gets exactly one field category and the Gospel "
           "themes it really explores. Write `[[Category:<name>]]` with the name for the page's wiki. "
           "The maintenance and tracking categories that SV templates add themselves (e.g. `{{SV WIP}}`, "
           "`{{SV cathopedia}}`) are the exception: they are not listed here and are never written by hand.\n"]
    for lang in LANGS:
        out.append(f"\n## {lang}\n\nRoot: {data['root']['names'][lang]}\n\n### Fields\n\n")

        def walk(items, depth):
            for item in items:
                definition = item.get("definition", {}).get("en", "")
                out.append(f"{'  ' * depth}- {item['names'][lang]} (`{item['key']}`)"
                           + (f": {definition}" if lang == "en" and definition else "") + "\n")
                walk(item.get("children", []), depth + 1)

        walk(data["fields"], 0)
        out.append(f"\n### {data['themes_root']['names'][lang]}\n\n")
        walk(data["themes"], 0)
    return "".join(out)


def main() -> None:
    target = ROOT / OUT
    target.mkdir(parents=True, exist_ok=True)
    (target / "templates.md").write_text(render_templates(ROOT), encoding="utf-8")
    (target / "categories.md").write_text(render_categories(ROOT), encoding="utf-8")
    print(f"wrote {OUT}/templates.md and {OUT}/categories.md")


if __name__ == "__main__":
    main()
